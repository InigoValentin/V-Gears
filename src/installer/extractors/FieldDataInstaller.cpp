bool FieldDataInstaller::IsAFieldFile(const Ogre::String& resource_name){
    return (
      !VGears::StringUtil::endsWith(resource_name, ".tex")
      && !VGears::StringUtil::endsWith(resource_name, ".tut")
      && !VGears::StringUtil::endsWith(resource_name, ".siz")
      && resource_name != "maplist"
    );
}

bool FieldDataInstaller::CollectSpawnPoints(const VGears::FLevelFilePtr& field){
    const size_t field_id = FieldData::FieldId(field->getName(), map_list_);
    // Decompile the script just so the MAPJUMPs can be collected. This is needed to construct the
    // full list of entries to each field.
    try{
        FF7FieldScriptGatewayCollector formatter(field->getName(), map_list_, spawn_points_, field_id);
        FieldDecompiler::Decompile(
          field->getName(), field->GetRawScript(), formatter, "", "EntityContainer = {}\n\n"
        );
    }
    catch (const ::DecompilerException& ex){
        std::cerr << "[WARNING] CollectSpawnPoints: decompiler failed for " << field->getName()
          << ": " << ex.what() << std::endl;
        return false;
    }
    const VGears::TriggersFilePtr& triggers = field->GetTriggers();
    if (triggers.isNull()){
        std::cerr << "CollectSpawnPoints: missing trigger data for " << field->getName() << std::endl;
        return false;
    }
    const auto& gateways = triggers->GetGateways();
    for (size_t i = 0; i < gateways.size(); i ++){
        if (gateways[i].destination_field_id == FieldData::INACTIVE_GATEWAY_ID) continue;
        SpawnPointDb::Record record;
        record.field_id = static_cast<u16>(field_id);
        record.gateway = gateways[i];
        record.gateway_index_or_map_jump_address = static_cast<u32>(i);
        FieldData::AddSpawnPoint(spawn_points_, record);
    }
    return true;
}

void FieldDataInstaller::PcFieldToVGearsField(const VGears::FLevelFilePtr& field){
    const FieldDecompiler::DecompiledScript decompiled = script_installer_.Install(field);
    map_writer_.WriteMap(field, decompiled);
    const float scale = FieldData::ScaleFactor(
      scale_factors_, FieldData::FieldId(field->getName(), map_list_)
    );
    background_installer_.Install(field, decompiled, scale);
    map_writer_.WriteWalkmesh(field);
    converted_map_list_.push_back(field->getName());
}
